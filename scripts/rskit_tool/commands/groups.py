"""Module-group documentation commands.

`toven.toml` `[groups.*]` is the single source of rskit's architectural layers.
These commands read `toven groups --output jsonl` and render the module index
and the layer diagram; selection and layering enforcement stay in Toven.
"""

from __future__ import annotations

import argparse
import dataclasses
import json
import os
from pathlib import Path

from ..cargo import metadata
from ..errors import ToolError
from ..paths import ROOT, WORKSPACES
from ..process import command_exists, run


@dataclasses.dataclass(frozen=True)
class Group:
    """A `[groups.<name>]` declaration as reported by `toven groups`."""

    name: str
    description: str
    modules: tuple[str, ...]
    # `None` means unrestricted: the group sits outside the layer stack.
    allow_groups: tuple[str, ...] | None


def add_parser(subparsers: argparse._SubParsersAction[argparse.ArgumentParser]) -> None:
    """Register group commands."""

    parser = subparsers.add_parser("groups", help="Module-group documentation")
    group_sub = parser.add_subparsers(dest="group_command", required=True)

    index = group_sub.add_parser("module-index", help="Generate docs/MODULE-INDEX.md")
    index.set_defaults(func=run_module_index)

    depgraphs = group_sub.add_parser("depgraphs", help="Generate dependency graph SVGs")
    depgraphs.add_argument("out_dir", nargs="?", default="docs/depgraphs")
    depgraphs.set_defaults(func=run_depgraphs)


def load_groups() -> list[Group]:
    """Read the declared groups from `toven groups --output jsonl`."""

    toven = os.environ.get("TOVEN", "toven")
    if not command_exists(toven):
        raise ToolError(f"error: {toven} is not installed or not in PATH (set TOVEN to override)")
    completed = run([toven, "groups", "--output", "jsonl"], capture=True)
    return parse_groups(completed.stdout)


def parse_groups(jsonl: str) -> list[Group]:
    """Parse `toven groups --output jsonl` records."""

    groups: list[Group] = []
    for line in jsonl.splitlines():
        if not line.strip():
            continue
        try:
            record = json.loads(line)
            allow = record["allow_groups"]
            groups.append(
                Group(
                    name=record["group"],
                    description=record.get("description") or "",
                    modules=tuple(member["module"].split(":", 1)[-1] for member in record["members"]),
                    allow_groups=None if allow is None else tuple(allow),
                )
            )
        except (json.JSONDecodeError, KeyError, TypeError) as error:
            raise ToolError(f"error: unexpected `toven groups` record {line!r}: {error}") from error
    return groups


def _layer_edges(groups: list[Group]) -> dict[str, set[str]]:
    """Map each layered group to the layered groups it may depend on.

    Unrestricted groups (`allow_groups` unset) sit outside the layer stack, so
    they and edges into them are left out.
    """

    layered = {group.name for group in groups if group.allow_groups is not None}
    return {
        group.name: set(group.allow_groups) & layered
        for group in groups
        if group.allow_groups is not None
    }


def _closure(node: str, deps: dict[str, set[str]], seen: set[str]) -> set[str]:
    """Collect every group transitively reachable from ``node``."""

    for child in deps.get(node, set()):
        if child not in seen:
            seen.add(child)
            _closure(child, deps, seen)
    return seen


def layer_order(groups: list[Group]) -> list[Group]:
    """Order groups bottom-up: layered groups by reach, then the unrestricted ones."""

    deps = _layer_edges(groups)
    reach = {name: len(_closure(name, deps, set())) for name in deps}
    layered = sorted((g for g in groups if g.name in deps), key=lambda g: (reach[g.name], g.name))
    unrestricted = sorted((g for g in groups if g.name not in deps), key=lambda g: g.name)
    return layered + unrestricted


def reduced_edges(deps: dict[str, set[str]]) -> dict[str, list[str]]:
    """Drop edges already implied through another direct dependency."""

    reduced: dict[str, list[str]] = {}
    for name, directs in deps.items():
        keep: list[str] = []
        for dependency in sorted(directs):
            via_others: set[str] = set()
            for other in directs - {dependency}:
                _closure(other, deps, via_others)
            if dependency not in via_others:
                keep.append(dependency)
        reduced[name] = keep
    return reduced


def build_module_index(groups: list[Group]) -> str:
    """Render docs/MODULE-INDEX.md."""

    lines = [
        "# Module Index by Group",
        "",
        "<!-- Auto-generated by scripts/rskit_tool.py groups module-index from `toven groups` - do not edit manually -->",
        "",
        "Groups are declared in `toven.toml` `[groups.*]`, listed bottom-up. Check one with `make check-<group>`.",
        "",
    ]
    for group in layer_order(groups):
        lines.append(f"## {group.name}  (`make check-{group.name}`)")
        lines.append("")
        if group.description:
            lines.append(f"{group.description}.")
        if group.allow_groups is None:
            lines.append("May depend on: any group.")
        else:
            lines.append(f"May depend on: {', '.join(group.allow_groups) or 'no other group'}.")
        lines.append("")
        lines.append(" · ".join(group.modules))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def run_module_index(_args: argparse.Namespace) -> int:
    """Generate docs/MODULE-INDEX.md."""

    output_path = ROOT / "docs" / "MODULE-INDEX.md"
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(build_module_index(load_groups()), encoding="utf-8")
    print(f"Generated {output_path}")
    return 0


def build_layer_dot(groups: list[Group]) -> str:
    """Build a Graphviz diagram of the layer stack with transitively reduced edges."""

    deps = _layer_edges(groups)
    reduced = reduced_edges(deps)
    ordered = [group for group in layer_order(groups) if group.name in deps]

    lines = [
        "digraph rskit_layers {",
        "  rankdir=TB;",
        "  splines=true;",
        '  node [shape=box, style="rounded,filled", fillcolor="#eef3fb", '
        'color="#5b6b7f", fontname="Helvetica"];',
        '  edge [color="#5b6b7f"];',
    ]
    for group in ordered:
        count = len(group.modules)
        plural = "module" if count == 1 else "modules"
        lines.append(f'  "{group.name}" [label="{group.name}\\n({count} {plural})"];')
    for group in ordered:
        for dependency in reduced[group.name]:
            lines.append(f'  "{group.name}" -> "{dependency}";')
    lines.append("}")
    return "\n".join(lines) + "\n"


def _rskit_package_names(manifest: Path) -> list[str]:
    """Return every resolved ``rskit-*`` package visible from ``manifest``."""

    data = metadata(manifest, no_deps=False)
    names = {
        str(package["name"])
        for package in data["packages"]  # type: ignore[index]
        if str(package["name"]).startswith("rskit-")
    }
    return sorted(names)


def run_depgraphs(args: argparse.Namespace) -> int:
    """Generate the dependency graph SVGs embedded in docs/DESIGN.md."""

    if not command_exists("cargo"):
        raise ToolError("error: cargo is not installed or not in PATH")
    if not command_exists("dot"):
        raise ToolError("error: dot (Graphviz) is not installed or not in PATH")
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    print(f"Generating dependency graphs into: {out_dir}")

    layers_file = out_dir / "graph-layers.svg"
    print(f"-> generating {layers_file}")
    with layers_file.open("w", encoding="utf-8") as output:
        run(["dot", "-Grankdir=TB", "-Tsvg"], stdin=build_layer_dot(load_groups()), stdout=output)
    print(f"   done: {layers_file}")

    # Crate-level detail: contrib adapters and the core crates they build on.
    # `--workspace-only` would hide every core crate, so instead include all
    # resolved rskit crates and let `dot` draw the contrib -> core edges.
    contrib_file = out_dir / "graph-contrib.svg"
    print(f"-> generating {contrib_file}")
    names = _rskit_package_names(WORKSPACES["contrib"])
    include_args: list[str] = []
    for name in names:
        include_args.extend(("--include", name))
    depgraph = run(
        [
            "cargo",
            "depgraph",
            "--manifest-path",
            str(WORKSPACES["contrib"]),
            *include_args,
            "--dedup-transitive-deps",
        ],
        capture=True,
    )
    with contrib_file.open("w", encoding="utf-8") as output:
        run(["dot", "-Grankdir=LR", "-Nshape=box", "-Tsvg"], stdin=depgraph.stdout, stdout=output)
    print(f"   done: {contrib_file}")

    print("All graphs generated successfully.")
    return 0
